export const DICTS = { ru, en }
export const LOCALES = ['ru', 'en']

export function normalizeLocale(value) {
  return value === 'en' ? 'en' : 'ru'
}

/** Returns `t(key, vars)` for a locale; falls back to Russian, then to the key itself. */
export function createT(locale) {
  const dict = DICTS[normalizeLocale(locale)]
  return (key, vars) => {
    const template = dict[key] ?? ru[key] ?? key
    if (!vars) return template
    return template.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m))
  }
}

/** Russian plural for "раздача": 1 раздача, 2 раздачи, 5 раздач. */
export function pluralTorrents(n, locale) {
  const abs = Math.abs(Math.trunc(Number(n) || 0))
  if (normalizeLocale(locale) === 'en') return abs === 1 ? 'torrent' : 'torrents'
  const m10 = abs % 10
  const m100 = abs % 100
  if (m100 >= 11 && m100 <= 14) return 'раздач'
  if (m10 === 1) return 'раздача'
  if (m10 >= 2 && m10 <= 4) return 'раздачи'
  return 'раздач'
}
